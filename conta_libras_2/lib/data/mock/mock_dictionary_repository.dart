  static List<TermModel> searchTerms(String query) {
    if (query.isEmpty) return terms;
    return terms.where((term) {
      return term.title.toLowerCase().contains(query.toLowerCase()) ||
             term.category.toLowerCase().contains(query.toLowerCase());
    }).toList();
  }
